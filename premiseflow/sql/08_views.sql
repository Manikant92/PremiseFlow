-- ---------------------------------------------------------------------------
-- Dependency graph: edges + recursive blast radius
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW CORE.V_DEPENDENCY_EDGES AS
SELECT DEPENDENCY_ID, SOURCE_OBJECT, SOURCE_TYPE, TARGET_OBJECT, TARGET_TYPE,
       RELATIONSHIP_TYPE, MATERIALITY, SENSITIVITY_NOTE
FROM CORE.ASSUMPTION_DEPENDENCIES
WHERE VALID_TO IS NULL;

-- Downstream closure from any node. Depth-capped to stay safe against cycles.
CREATE OR REPLACE VIEW CORE.V_BLAST_RADIUS AS
WITH RECURSIVE walk AS (
  SELECT e.SOURCE_OBJECT AS ROOT_OBJECT, e.SOURCE_OBJECT, e.SOURCE_TYPE,
         e.TARGET_OBJECT, e.TARGET_TYPE, e.RELATIONSHIP_TYPE, e.MATERIALITY,
         e.SENSITIVITY_NOTE, 1 AS DEPTH,
         e.SOURCE_OBJECT||' > '||e.TARGET_OBJECT AS PATH
  FROM CORE.V_DEPENDENCY_EDGES e
  UNION ALL
  SELECT w.ROOT_OBJECT, e.SOURCE_OBJECT, e.SOURCE_TYPE,
         e.TARGET_OBJECT, e.TARGET_TYPE, e.RELATIONSHIP_TYPE, e.MATERIALITY,
         e.SENSITIVITY_NOTE, w.DEPTH + 1,
         w.PATH||' > '||e.TARGET_OBJECT
  FROM walk w
  JOIN CORE.V_DEPENDENCY_EDGES e ON e.SOURCE_OBJECT = w.TARGET_OBJECT
  WHERE w.DEPTH < 6 AND POSITION(e.TARGET_OBJECT, w.PATH) = 0
)
SELECT ROOT_OBJECT, SOURCE_OBJECT, SOURCE_TYPE, TARGET_OBJECT, TARGET_TYPE,
       RELATIONSHIP_TYPE, MATERIALITY, SENSITIVITY_NOTE, DEPTH, PATH
FROM walk;

-- Decisions exposed to an assumption, with the version they relied on
CREATE OR REPLACE VIEW CORE.V_AFFECTED_DECISIONS AS
SELECT
  dd.ASSUMPTION_ID, dd.VERSION_ID AS RELIED_ON_VERSION_ID, dd.RELIANCE_STRENGTH, dd.RELIANCE_NOTE,
  d.DECISION_ID, d.DECISION_REF, d.TITLE, d.COMMITTEE, d.DECISION_DATE,
  d.DECISION_TEXT, d.RATIONALE, d.APPROVED_BY, d.MATERIALITY, d.GOVERNANCE_STATUS,
  d.STATUS_CHANGED_AT, d.SOURCE_DOCUMENT,
  r.REASSESSMENT_ID, r.STATUS AS REASSESSMENT_STATUS, r.TRIGGERED_AT,
  r.IMPACT_SUMMARY, r.AI_RECOMMENDATION
FROM CORE.DECISION_DEPENDENCIES dd
JOIN CORE.DECISIONS d ON d.DECISION_ID = dd.DECISION_ID
LEFT JOIN CORE.REASSESSMENTS r
  ON r.DECISION_ID = dd.DECISION_ID AND r.ASSUMPTION_ID = dd.ASSUMPTION_ID
     AND r.STATUS IN ('OPEN','IN_REVIEW');

-- ---------------------------------------------------------------------------
-- Scenario comparison + audit timeline
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW CORE.V_SCENARIO_COMPARISON AS
SELECT
  s.RUN_ID, s.ASSUMPTION_ID, s.SCENARIO_ID, s.SCENARIO_TYPE, s.NAME AS SCENARIO_NAME,
  s.RETENTION_INPUT, s.CREATED_AT, s.CREATED_BY,
  r.METRIC_ID, r.METRIC_NAME, r.METRIC_VALUE, r.UNIT, r.FORMULA, r.INPUTS,
  r.BREACHES_LIMIT, r.POC_DISCLAIMER,
  m.INTERNAL_LIMIT, m.REGULATORY_MIN
FROM CORE.SCENARIOS s
JOIN CORE.SCENARIO_RESULTS r ON r.SCENARIO_ID = s.SCENARIO_ID
LEFT JOIN CORE.RISK_METRICS m ON m.METRIC_ID = r.METRIC_ID;

CREATE OR REPLACE VIEW AUDIT.V_AUDIT_TIMELINE AS
SELECT
  e.EVENT_ID, e.EVENT_TS, e.EVENT_TYPE, e.OBJECT_TYPE, e.OBJECT_ID,
  e.ACTOR_TYPE, e.ACTOR_ID, e.OLD_STATE, e.NEW_STATE,
  e.EVIDENCE_REFERENCE, e.RUN_ID, e.RATIONALE, e.PAYLOAD,
  CASE e.EVENT_TYPE
    WHEN 'ASSUMPTION_CREATED'        THEN 10
    WHEN 'EVIDENCE_ATTACHED'         THEN 20
    WHEN 'VERSION_APPROVED'          THEN 30
    WHEN 'OBSERVATION_GENERATED'     THEN 40
    WHEN 'CHALLENGE_DETECTED'        THEN 50
    WHEN 'BREACH_DETECTED'           THEN 60
    WHEN 'BREACH_CONFIRMED'          THEN 70
    WHEN 'IMPACT_SIMULATED'          THEN 80
    WHEN 'DECISION_REOPENED'         THEN 90
    WHEN 'NEW_VERSION_PROPOSED'      THEN 100
    WHEN 'NEW_VERSION_APPROVED'      THEN 110
    ELSE 999 END AS STAGE_ORDER
FROM AUDIT.AUDIT_EVENTS e;

SELECT 'views ready' AS STATUS,
  (SELECT COUNT(*) FROM CORE.V_ASSUMPTION_CURRENT) AS ASSUMPTIONS,
  (SELECT COUNT(*) FROM CORE.V_BLAST_RADIUS WHERE ROOT_OBJECT='A-DEP-001') AS ADEP001_BLAST_EDGES,
  (SELECT ROUND(HQLA_AMOUNT/1e6,2) FROM CORE.LIQUIDITY_INPUTS) AS HQLA_M,
  (SELECT ROUND(RETAIL_STABLE_DEPOSITS/1e6,2) FROM CORE.LIQUIDITY_INPUTS) AS RETAIL_STABLE_M;
