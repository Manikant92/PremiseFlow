-- ---------------------------------------------------------------------------
-- Current state of every assumption: contract + latest observation
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW CORE.V_ASSUMPTION_CURRENT AS
WITH latest_obs AS (
  SELECT o.* FROM CORE.DT_ASSUMPTION_OBSERVATIONS o
  QUALIFY ROW_NUMBER() OVER (PARTITION BY o.ASSUMPTION_ID ORDER BY o.OBSERVATION_DATE DESC) = 1
),
latest_chal AS (
  SELECT c.* FROM CORE.ASSUMPTION_CHALLENGES c
  QUALIFY ROW_NUMBER() OVER (PARTITION BY c.ASSUMPTION_ID ORDER BY c.EVALUATED_AT DESC) = 1
)
SELECT
  a.ASSUMPTION_ID, a.NAME, a.STATEMENT, a.DOMAIN, a.OWNER_ROLE, a.MATERIALITY,
  a.STATUS, a.CURRENT_VERSION, a.METRIC_CODE, a.LAST_VALIDATED_AT,
  v.VERSION_ID, v.VERSION_NUMBER, v.EXPECTED_VALUE, v.LOWER_BOUND, v.UPPER_BOUND,
  v.CHALLENGE_THRESHOLD, v.BREACH_THRESHOLD, v.PERSISTENCE_DAYS, v.DIRECTION,
  v.VALIDITY_ENVELOPE, v.EVIDENCE_SUMMARY, v.APPROVED_BY, v.APPROVED_AT,
  o.OBSERVATION_DATE   AS LATEST_OBSERVATION_DATE,
  o.OBSERVED_VALUE     AS LATEST_OBSERVED_VALUE,
  o.SAMPLE_SIZE        AS LATEST_SAMPLE_SIZE,
  o.OBSERVED_VALUE - v.EXPECTED_VALUE AS DEVIATION,
  CASE WHEN v.EXPECTED_VALUE <> 0
       THEN (o.OBSERVED_VALUE - v.EXPECTED_VALUE) / ABS(v.EXPECTED_VALUE) END AS DEVIATION_PCT,
  ch.CHALLENGE_ID      AS LATEST_CHALLENGE_ID,
  ch.STATUS            AS LATEST_CHALLENGE_STATUS,
  ch.PERSISTENCE_DAYS  AS OBSERVED_PERSISTENCE_DAYS,
  ch.CONFIDENCE        AS LATEST_CONFIDENCE,
  ch.CHANGE_POINT_DATE,
  ch.EXPLANATION       AS LATEST_EXPLANATION,
  (SELECT COUNT(*) FROM CORE.ASSUMPTION_DEPENDENCIES d
    WHERE d.SOURCE_OBJECT = a.ASSUMPTION_ID AND d.VALID_TO IS NULL)      AS DIRECT_DEPENDENCY_COUNT,
  (SELECT COUNT(*) FROM CORE.DECISION_DEPENDENCIES dd
    WHERE dd.ASSUMPTION_ID = a.ASSUMPTION_ID)                            AS DEPENDENT_DECISION_COUNT
FROM CORE.ASSUMPTIONS a
JOIN CORE.ASSUMPTION_VERSIONS v
  ON v.ASSUMPTION_ID = a.ASSUMPTION_ID AND v.IS_CURRENT
LEFT JOIN latest_obs  o ON o.ASSUMPTION_ID = a.ASSUMPTION_ID
LEFT JOIN latest_chal ch ON ch.ASSUMPTION_ID = a.ASSUMPTION_ID;

-- Executive counters
CREATE OR REPLACE VIEW CORE.V_ASSUMPTION_HEALTH AS
SELECT
  COUNT(*)                                             AS ACTIVE_ASSUMPTIONS,
  COUNT_IF(STATUS='VALID')                             AS VALID_COUNT,
  COUNT_IF(STATUS='WATCH')                             AS WATCH_COUNT,
  COUNT_IF(STATUS='CHALLENGED')                         AS CHALLENGED_COUNT,
  COUNT_IF(STATUS='UNDER_REVIEW')                      AS UNDER_REVIEW_COUNT,
  COUNT_IF(STATUS='BREACHED')                          AS BREACHED_COUNT,
  COUNT_IF(STATUS='BREACHED' AND MATERIALITY='CRITICAL') AS CRITICAL_EXPOSURE_COUNT,
  (SELECT COUNT(*) FROM CORE.DECISIONS WHERE GOVERNANCE_STATUS='REASSESSMENT_REQUIRED')
                                                       AS DECISIONS_REQUIRING_REASSESSMENT,
  (SELECT COUNT(*) FROM CORE.REASSESSMENTS WHERE STATUS IN ('OPEN','IN_REVIEW'))
                                                       AS OPEN_REASSESSMENTS
FROM CORE.ASSUMPTIONS
WHERE STATUS <> 'RETIRED';

-- ---------------------------------------------------------------------------
-- The masking view: aggregate looks fine, the governed cohort does not
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW CORE.V_DEPOSIT_MASKING AS
WITH base AS (
  SELECT d.*, cfg.BREAK_DATE, cfg.SPINE_START_DATE, cfg.DEMO_END_DATE,
         FIRST_VALUE(d.TOTAL_DEPOSITS) OVER (ORDER BY d.BALANCE_DATE)            AS TOTAL_AT_START,
         FIRST_VALUE(d.GOVERNED_STABLE_DEPOSITS) OVER (ORDER BY d.BALANCE_DATE)  AS GOVERNED_AT_START
  FROM CORE.DT_DEPOSIT_DAILY d JOIN RAW.V_GEN_CONFIG cfg ON TRUE
)
SELECT
  BALANCE_DATE, BREAK_DATE,
  BALANCE_DATE >= BREAK_DATE                                     AS IS_POST_BREAK,
  TOTAL_DEPOSITS, INCUMBENT_DEPOSITS, NEW_CUSTOMER_DEPOSITS,
  PROMOTIONAL_DEPOSITS, GOVERNED_STABLE_DEPOSITS, TERM_DEPOSITS,
  WHOLESALE_LIKE_DEPOSITS, ACTIVE_CUSTOMERS,
  TOTAL_DEPOSITS / NULLIF(TOTAL_AT_START,0) - 1                  AS TOTAL_DEPOSIT_GROWTH,
  GOVERNED_STABLE_DEPOSITS / NULLIF(GOVERNED_AT_START,0) - 1      AS GOVERNED_DEPOSIT_GROWTH,
  PROMOTIONAL_DEPOSITS / NULLIF(TOTAL_DEPOSITS,0)                 AS PROMOTIONAL_FUNDING_SHARE
FROM base;

