-- ---------------------------------------------------------------------------
-- Simplified liquidity inputs, derived from the synthetic balance sheet.
-- HQLA is calibrated so that the APPROVED premise (90% retention) yields an
-- LCR of ~118%, which is the number the ALCO decision was taken on.
-- ---------------------------------------------------------------------------
DELETE FROM CORE.LIQUIDITY_INPUTS;
INSERT INTO CORE.LIQUIDITY_INPUTS
 (AS_OF_DATE, HQLA_AMOUNT, RETAIL_STABLE_DEPOSITS, RETAIL_LESS_STABLE_DEPOSITS,
  WHOLESALE_FUNDING, OTHER_OUTFLOWS, EXPECTED_INFLOWS,
  STABLE_RUNOFF_RATE, LESS_STABLE_RUNOFF_RATE, WHOLESALE_RUNOFF_RATE,
  AVG_FUNDING_COST_PCT, REPLACEMENT_FUNDING_SPREAD_BPS, NOTES)
WITH bs AS (
  SELECT d.BALANCE_DATE AS AS_OF_DATE,
         d.GOVERNED_STABLE_DEPOSITS                                   AS RETAIL_STABLE,
         d.TOTAL_DEPOSITS - d.GOVERNED_STABLE_DEPOSITS
           - d.WHOLESALE_LIKE_DEPOSITS                                AS RETAIL_LESS_STABLE,
         d.WHOLESALE_LIKE_DEPOSITS                                    AS WHOLESALE,
         d.TOTAL_DEPOSITS * 0.06                                      AS OTHER_OUT,
         d.TOTAL_DEPOSITS
  FROM CORE.DT_DEPOSIT_DAILY d
  JOIN RAW.V_GEN_CONFIG cfg ON d.BALANCE_DATE = cfg.DEMO_END_DATE
),
calib AS (
  SELECT bs.*,
         0.05 AS STABLE_RR, 0.12 AS LESS_RR, 0.25 AS WHOLESALE_RR,
         RETAIL_STABLE*0.05 + RETAIL_LESS_STABLE*0.12 + WHOLESALE*0.25 + OTHER_OUT AS GROSS_OUT_BASE
  FROM bs
)
SELECT
  AS_OF_DATE,
  -- HQLA pinned so baseline LCR = 118%
  ROUND(1.18 * (GROSS_OUT_BASE - LEAST(GROSS_OUT_BASE*0.35, GROSS_OUT_BASE*0.75)), 2) AS HQLA_AMOUNT,
  ROUND(RETAIL_STABLE,2), ROUND(RETAIL_LESS_STABLE,2), ROUND(WHOLESALE,2),
  ROUND(OTHER_OUT,2), ROUND(GROSS_OUT_BASE*0.35,2),
  STABLE_RR, LESS_RR, WHOLESALE_RR,
  0.0225, 145.0,
  'Synthetic balance sheet as at the demo end date. Runoff rates and the retention '||
  'sensitivity coefficient are illustrative POC parameters, not regulatory calibrations.'
FROM calib;

